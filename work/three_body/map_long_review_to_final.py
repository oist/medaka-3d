def code_hashes():
    paths = set(PINS) | {Path(__file__).resolve()}
    for module in tuple(sys.modules.values()):
        filename = getattr(module, "__file__", None)
        if filename:
            path = Path(filename).resolve()
            if path.suffix == ".py" and path.is_relative_to(REPO) and ".venv" not in path.parts:
                paths.add(path)
    return {str(p): review.sha256(p) for p in sorted(paths)}


def guard_completed(completed):
    chain = completed["chain"]
    require(
        completed.get("final_audit_complete") is False, "final loader scope must remain explicit"
    )
    frames = completed["candidate"]["frame_idx"]
    require(
        frames.dtype == np.dtype("int64")
        and frames.shape == (native.STOP - native.FIRST,)
        and np.array_equal(frames, np.arange(native.FIRST, native.STOP, dtype=np.int64)),
        "completed full30 native candidate required; no prefix fallback",
    )
    require(
        completed["checkpoint_metadata"]["processed_frames"] == native.STOP - native.FIRST
        and completed["checkpoint_metadata"]["previous_frame"] == native.STOP - 1,
        "terminal checkpoint scope differs",
    )
    require(
        chain["final_record"]["params"]["through_frame"] == native.STOP,
        "terminal producer endpoint differs",
    )
    return chain


def anchor_arrays(candidate, frames):
    """Select current final rows only; never reuse pack/prefix slot coordinates."""
    native_frames = np.asarray(frames)
    require(
        native_frames.shape == (3,)
        and native_frames.dtype.kind in "iu"
        and np.all(np.diff(native_frames.astype(np.int64)) > 0),
        "three ordered native anchors required",
    )
    positions = np.searchsorted(candidate["frame_idx"], native_frames)
    require(
        np.all(positions < len(candidate["frame_idx"]))
        and np.array_equal(candidate["frame_idx"][positions], native_frames),
        "anchor outside completed candidate",
    )
    return {key: candidate[key][positions].copy() for key in ANCHOR_KEYS}


def input_item(record, path, digest):
    final.legacy.input_binding(record, Path(path).resolve(), digest)


def verify_source_binding(chain, parsed, pack_summary, pack, evidence):
    """Join the review's exact consumed chunk to final inputs, not to prefix poses."""
    root, record = chain["final_run"], chain["final_record"]
    consumed = final.legacy.json_output(record, "consumed_chunks", root / "consumed_chunks.json")
    native.validate_consumed_ranges(consumed)
    fixed = chain["binding"]["inputs"]
    declared = pack_summary["consumed_record"]
    index = declared["index"]
    require(type(index) is int and 0 <= index < len(consumed), "invalid pack consumed index")
    equal(consumed[index], declared, "pack and final consumed chunk proofs differ")
    attempt = native.checked_relative(
        Path(fixed["input_stage_root"]).resolve(strict=True), declared["attempt_path"]
    )
    manifest_path = attempt / "manifest.json"
    seal_path = attempt / "staging.provenance.json"
    require(
        Path(pack_summary["source_manifest"]).resolve(strict=True) == manifest_path,
        "pack manifest path differs from final chunk",
    )
    evidence.add(manifest_path, declared["manifest_sha256"])
    evidence.add(seal_path, declared["provenance_sha256"])
    manifest = review.document(manifest_path.read_bytes(), "final consumed manifest")
    require(
        parsed.manifest_bytes == manifest_path.read_bytes(), "review original manifest bytes differ"
    )
    source = review.document(seal_path.read_bytes(), "detector seal")
    require(
        source.get("stage") == "prepare_independent_mask_chunk" and source.get("status") == "ok",
        "successful consumed detector source required",
    )
    equal(source["params"]["binding"], fixed["detector_binding"], "final detector binding differs")
    raw.validate_source(manifest, declared, fixed["detector_binding"])
    require(manifest["protocol_sha256"] == fixed["protocol_sha256"], "final raw protocol differs")
    outputs = {
        key: dict(path=str(Path(v["path"]).resolve()), sha256=v["sha256"])
        for key, v in source["outputs"].items()
    }
    equal(outputs, declared["output_hashes"], "consumed detector output membership differs")
    final.legacy.output_binding(source, manifest_path, declared["manifest_sha256"])
    pack_record = review.document((pack / "review.provenance.json").read_bytes(), "pack seal")
    for p, digest in (
        (manifest_path, declared["manifest_sha256"]),
        (seal_path, declared["provenance_sha256"]),
    ):
        input_item(pack_record, p, digest)
    # The prefix producer provides only provenance/config here. Its coordinates are never opened.
    prefix = raw.local(pack_summary["producer_run"])
    prefix_seal = prefix / "continuation.provenance.json"
    expected = pack_record["inputs"].get(str(prefix_seal))
    require(expected is not None, "pack prefix producer is unbound")
    evidence.add(prefix_seal, expected["sha256"])
    producer = review.document(prefix_seal.read_bytes(), "prefix producer")
    require(
        producer.get("stage") == "three_body_long_continuation" and producer.get("status") == "ok",
        "pack prefix producer must have succeeded",
    )
    shared = fixed["seed"]["SL_and_calibration_sha256"]
    equal(
        producer["params"]["bindings"]["inputs"]["seed"]["SL_and_calibration_sha256"],
        shared,
        "pack prefix and final SL/calibration bindings differ",
    )
    videos = {}
    displayed = []
    for view in VIEWS:
        descriptor = manifest["raw"][view]
        path = native.checked_relative(attempt, descriptor["path"])
        digest = descriptor["sha256"]
        link = declared["raw_hardlinks"][view]
        canonical = raw.local(link["source_path"])
        expected = fixed["detector_inputs"]["video:" + view]
        stat = path.stat()
        require(
            Path(expected["path"]).resolve() == canonical
            and expected["sha256"] == digest
            and Path(link["path"]).resolve() == path
            and link["sha256"] == digest
            and os.path.samefile(path, canonical)
            and (stat.st_dev, stat.st_ino, stat.st_size, stat.st_mtime_ns)
            == (link["device"], link["inode"], link["bytes"], link["mtime_ns"]),
            "original MP4 identity/hardlink differs",
        )
        final.legacy.output_binding(source, path, digest)
        input_item(pack_record, path, digest)
        input_item(source, canonical, digest)
        evidence.add(canonical, digest)
        evidence.add(path, digest)
        videos[view] = path
        for frame in parsed.anchor_frames:
            name = f"frames/f{int(frame)}_{view}.jpg"
            image = pack / name
            expected_image = pack_record["outputs"].get(name)
            require(
                expected_image is not None and Path(expected_image["path"]).resolve() == image,
                "human-selected displayed native image is not bound",
            )
            evidence.add(image, expected_image["sha256"])
            displayed.append(
                dict(
                    frame=int(frame),
                    view=view,
                    path=str(image),
                    sha256=expected_image["sha256"],
                    encoding="lossy JPEG96; source BGR checked independently below",
                )
            )
    return dict(
        manifest=manifest,
        videos=videos,
        shared=copy.deepcopy(shared),
        displayed=displayed,
        proof=dict(
            final_consumed_index=index,
            consumed_record=copy.deepcopy(declared),
            pack_prefix_producer=str(prefix),
            prefix_coordinate_arrays_opened=False,
            prefix_candidate_sha256=producer["outputs"]["candidate"]["sha256"],
            final_candidate_sha256=record["outputs"]["candidate"]["sha256"],
            same_prefix_final_SL_calibration=True,
            same_final_consumed_chunk=True,
            original_MP4_sha256={v: manifest["raw"][v]["sha256"] for v in VIEWS},
        ),
    )


def load_anchor_geometry(shared, context, frames, evidence):
    """Load only registered SL and camera inputs; preserve native within-frame row order."""
    shared = {str(raw.local(p)): d for p, d in shared.items()}
    require(len(shared) == 7, "exactly three SL plus four calibration inputs required")
    for p, d in shared.items():
        evidence.add(p, d)
    manifests = [Path(p) for p in shared if Path(p).name == "calibration_manifest.json"]
    require(len(manifests) == 1, "exactly one calibration manifest required")
    calibration_manifest = manifests[0]
    manifest = review.document(calibration_manifest.read_bytes(), "calibration manifest")
    models = [
        native.checked_relative(calibration_manifest.parent, row["path"])
        for row in manifest["model_files"]
    ]
    calibration = {str(p): shared[str(p)] for p in [calibration_manifest, *models]}
    require(len(models) == 3 and len(calibration) == 4, "three registered camera models required")
    points_paths = {
        view: Path(p)
        for view in VIEWS
        for p in shared
        if Path(p).name == f"{baseline.EXPERIMENT}__{view}.npz"
    }
    require(
        set(points_paths) == set(VIEWS)
        and set(shared) == set(calibration) | {str(p) for p in points_paths.values()},
        "SL/calibration file membership differs",
    )
    rig = load_rig(calibration_manifest.parent)
    equal(
        final.COMMON.normalize([dataclasses.asdict(camera) for camera in rig.cameras]),
        context["cameras"],
        "actual rig differs from final state context",
    )
    require(
        list(rig.views) == context["views"] == list(VIEWS)
        and rig.world_units == context["world_units"] == "mm",
        "camera order/world units differ",
    )
    interval = np.arange(int(frames[0]), int(frames[-1]) + 1, dtype=np.int64)
    nodes = baseline.RegisteredNodes(points_paths, interval)
    points = {int(frame): {v: nodes.at(v, int(frame)).copy() for v in VIEWS} for frame in frames}
    return rig, points, calibration


def decode_anchor_images(videos, manifest, frames, *, capture_factory=None):
    """Three explicit native seeks, nine raw images, no surrounding/video-wide decode."""
    require(
        len(frames) == 3 and len(set(map(int, frames))) == 3, "three unique anchor frames required"
    )
    rows = []
    for native_frame in frames:
        frame = int(native_frame)
        iterator = raw.iter_native(
            videos, manifest, frame, frame + 1, capture_factory=capture_factory
        )
        try:
            actual, images = next(iterator)
            require(actual == frame, "native decoder returned wrong frame")
            for view in VIEWS:
                bgr = images[view]
                rows.append(
                    dict(
                        frame=frame,
                        view=view,
                        shape=list(bgr.shape),
                        dtype=bgr.dtype.str,
                        bgr_sha256=hashlib.sha256(np.ascontiguousarray(bgr).tobytes()).hexdigest(),
                    )
                )
            require(next(iterator, None) is None, "single-anchor decoder yielded extra frame")
        finally:
            iterator.close()
    require(len(rows) == 9, "exactly nine native images required")
    return rows


def run_mapping(final_supervisor, review_pack, review_path, output):
    output = Path(output).resolve()
    require(
        output.is_relative_to(REPO / "work") and not output.exists(),
        "new workspace output required",
    )
    codes = code_hashes()
    evidence = final.phase.Digests()
    for path, digest in codes.items():
        evidence.add(path, digest)
    for path, digest in {**final.PINS, **PINS}.items():
        evidence.add(path, digest)
    output.mkdir(parents=True)
    document_evidence = None
    with provenance(STAGE, output, name="mapping") as record:
        try:
            snapshot(codes, output, record)
            # No human-document or prefix fallback before the successful full-run gate.
            completed = final.load_completed_final(final_supervisor, evidence)
            chain = guard_completed(completed)
            parsed, pack_summary, document_evidence = review.load_document(review_pack, review_path)
            pack = raw.local(review_pack)
            for path, digest in document_evidence.hashes.items():
                if path.is_relative_to(REPO):
                    evidence.add(path, digest)
                else:
                    require(
                        path == Path(review_path).expanduser().resolve(strict=True),
                        "only the explicit human JSON may be external",
                    )
            source = verify_source_binding(chain, parsed, pack_summary, pack, evidence)
            anchors = anchor_arrays(completed["candidate"], parsed.anchor_frames)
            context = copy.deepcopy(completed["checkpoint_metadata"]["context"])
            final_digests = {k: copy.deepcopy(completed["exact_backtrace"][k]) for k in ANCHOR_KEYS}
            # Release full retained history before the small local raw/matching work.
            del completed
            rig, points, calibration = load_anchor_geometry(
                source["shared"], context, parsed.anchor_frames, evidence
            )
            native_rows = decode_anchor_images(
                source["videos"], source["manifest"], parsed.anchor_frames
            )
            projection = Path(review.evaluate_review.__file__).resolve()
            evidence.add(projection)
            original_arrays = {k: review.array_sha256(v) for k, v in anchors.items()}
            mapping = review.match_anchor_rows(
                parsed,
                anchors,
                rig,
                points,
                candidate_sha256=chain["final_record"]["outputs"]["candidate"]["sha256"],
                calibration_sha256=calibration,
                projection_origin_sha256=evidence.paths[str(projection)],
            )
            require(
                original_arrays == {k: review.array_sha256(v) for k, v in anchors.items()},
                "matching changed final anchor inputs",
            )
            for name, data in (
                ("original_review.json", parsed.review_bytes),
                ("original_source_manifest.json", parsed.manifest_bytes),
            ):
                path = output / name
                with path.open("xb") as stream:
                    stream.write(data)
                record.output(name, path, sha256=review.sha256(path))
            archive = output / "final_anchor_rows.npz"
            np.savez_compressed(archive, **anchors)
            record.output("final_anchor_rows", archive, sha256=review.sha256(archive))
            save_json(output / "mapping.json", mapping, record, "local_mapping")
            save_json(
                output / "native_anchor_images.json", native_rows, record, "native_anchor_images"
            )
            summary = dict(
                schema=STAGE,
                status="local_endpoints_mapped_to_verified_final_candidate",
                review_pack=str(pack),
                original_review_path=str(Path(review_path).expanduser().resolve()),
                review_sha256=hashlib.sha256(parsed.review_bytes).hexdigest(),
                manifest_sha256=hashlib.sha256(parsed.manifest_bytes).hexdigest(),
                actual_anchor_frames=parsed.anchor_frames.tolist(),
                source_binding=source["proof"],
                displayed_native_files=source["displayed"],
                final_run=str(chain["final_run"]),
                full_native_interval=[native.FIRST, native.STOP],
                final_candidate_files_verified=True,
                final_state_codec_and_backtrace_verified=True,
                final_audit_complete=False,
                full_run_independent_support_or_identity_audit=False,
                final_array_digests=final_digests,
                anchor_array_digests=original_arrays,
                SL_calibration_sha256=source["shared"],
                native_raw_images_redecoded=9,
                original_MP4_files_rehashed=True,
                mask_arrays_decoded=False,
                human_status_preserved=parsed.review["status"],
                elapsed_review_seconds=parsed.review["elapsed_review_seconds"],
                local_labels=list(review.ANIMALS),
                requested_endpoints=9,
                requested_links=6,
                staged_links=sum(
                    row["status"] == "staged_endpoint_link" for row in mapping["links"]
                ),
                biological_ID_names_assigned=False,
                dense_trajectory_modified=False,
                raw_review_cleared=False,
                original_review_flags_preserved=True,
                production_correction_ready=False,
                GPU_used=False,
                independent_ID_truth_created=False,
                scope="Local human assertions rematched against current final geometry. "
                "Endpoint links do not certify the interval interior or biological identity.",
            )
            save_json(output / "summary.json", summary, record, "summary")
        finally:
            for path, digest in evidence.paths.items():
                record.input(path, path, sha256=digest)
            if document_evidence is not None:
                for path, digest in document_evidence.hashes.items():
                    record.input(str(path), path, sha256=digest)
                document_evidence.final_guard()
            require(code_hashes() == codes, "loaded mapping source set changed")
            evidence.final_guard()
            final_outputs(record)
        record.param("all_opened_input_source_snapshot_output_sha_unchanged", True)
    return output


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    for flag in ("final-supervisor", "review-pack", "review", "output"):
        parser.add_argument("--" + flag, required=True, type=Path)
    args = parser.parse_args(argv)
    return run_mapping(args.final_supervisor, args.review_pack, args.review, args.output)


if __name__ == "__main__":
    main()
