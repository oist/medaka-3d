"""B0.3 — re-score round-7 checkpoints on crossing frames only.

The production architecture was chosen on metrics averaged over *all* validation
frames, which are overwhelmingly well-separated fish. A model can win on average
and lose exactly where identity is decided. This splits the same validation set
into **crossing** and **separated** frames and scores each architecture on both.

No inference is run and no GPU is needed. Every round-7 training run saved its
own validation ground truth and predictions side by side:

    <run>/labels_gt.val.0.slp
    <run>/labels_pr.val.0.slp

so this is a re-scoring of predictions that already exist.

**Metric.** Greedy one-to-one matching of predicted to ground-truth instances by
mean node distance. A GT instance counts as detected when its matched prediction
is within ``tolerance`` px, reported at several tolerances because a single
threshold hides the shape of the failure. Localisation error is reported over
matched pairs only, so recall and precision of position stay separable.

Run:
    .venv\\Scripts\\python.exe tools/b03_score_checkpoints_at_crossings.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import sleap_io as sio

from medaka3d import load_paths

ROUND7 = "sleap_models/retrain_20260704"

#: Runs to compare, per view: (label, run directory name).
#: The `top` runs shipped EMPTY labels_pr.val.0.slp files, so their predictions
#: were regenerated by tools/b03_run_top_inference.py into work_dir. See
#: REGENERATED_TOP below.
#:
#: RESOLUTION MATTERS, and getting this wrong invalidates the comparison.
#: `round7_260704.bottomup_*` trained at `preprocessing.scale = 0.5`;
#: `round7s1.bottomup_*` and both top-down models at `scale = 1.0`. Scoring
#: top-down against the 0.5 run confounds architecture with input resolution — at
#: half scale two fish 25 px apart are 12.5 px apart in the model's input, which
#: is precisely the regime under test. The full-resolution `round7s1` run is the
#: PRIMARY bottom-up arm; the half-resolution one is reported only as a labelled
#: sensitivity arm.
ARCHITECTURES = {
    "top": [
        ("top-down (production)", "round7_260704.centered_instance_n1295"),
        ("bottom-up full-res (primary)", "round7s1.bottomup_n1295"),
        ("bottom-up half-res (sensitivity)", "round7_260704.bottomup_n1295"),
    ],
    "side": [
        ("top-down (fallback)", "round7_260704.centered_instance_n2590"),
        ("bottom-up full-res (primary)", "round7s1.bottomup_n2590"),
        ("bottom-up half-res (sensitivity)", "round7_260704.bottomup_n2590"),
    ],
}

#: Regenerated top predictions: run label -> (gt file, pr file) under work_dir.
REGENERATED_TOP = {
    "top-down (production)": ("labels_gt.val.remapped.slp", "labels_pr.val.topdown.slp"),
    "bottom-up full-res (primary)": (
        "labels_gt.val.remapped.slp",
        "labels_pr.val.bottomup_full.slp",
    ),
    "bottom-up half-res (sensitivity)": (
        "labels_gt.val.remapped.slp",
        "labels_pr.val.bottomup_half.slp",
    ),
}

#: A frame is a "crossing" when two GT instances have nodes this close.
#: 25 px is ~0.25 of the median labelled mouth-tail span (B0.1).
CROSSING_PX = 25.0
TOLERANCES = (5.0, 10.0, 20.0, 40.0)


def instance_points(instance) -> np.ndarray:
    return np.asarray(instance.numpy(), dtype=float)[:, :2]


def min_node_gap(a: np.ndarray, b: np.ndarray) -> float:
    gaps = [
        float(np.hypot(*(pa - pb)))
        for pa in a
        for pb in b
        if not (np.isnan(pa).any() or np.isnan(pb).any())
    ]
    return min(gaps) if gaps else float("inf")


def mean_node_error(gt: np.ndarray, pr: np.ndarray) -> float:
    """Mean distance over nodes visible in BOTH; inf if they share none."""
    usable = ~(np.isnan(gt).any(axis=1) | np.isnan(pr).any(axis=1))
    if not usable.any():
        return float("inf")
    return float(np.hypot(*(gt[usable] - pr[usable]).T).mean())


def match_greedy(gt: list[np.ndarray], pr: list[np.ndarray]) -> list[tuple[int, int, float]]:
    """One-to-one (gt_index, pr_index, error), closest pair first."""
    pairs = sorted(
        ((mean_node_error(g, p), i, j) for i, g in enumerate(gt) for j, p in enumerate(pr)),
        key=lambda t: t[0],
    )
    used_gt: set[int] = set()
    used_pr: set[int] = set()
    out: list[tuple[int, int, float]] = []
    for error, i, j in pairs:
        if not np.isfinite(error) or i in used_gt or j in used_pr:
            continue
        used_gt.add(i)
        used_pr.add(j)
        out.append((i, j, error))
    return out


def score(run_dir: Path, override: tuple[Path, Path] | None = None) -> dict | None:
    if override is not None:
        gt_path, pr_path = override
    else:
        gt_path, pr_path = run_dir / "labels_gt.val.0.slp", run_dir / "labels_pr.val.0.slp"
    if not (gt_path.is_file() and pr_path.is_file()):
        return None

    gt_labels, pr_labels = sio.load_slp(str(gt_path)), sio.load_slp(str(pr_path))
    if not pr_labels.labeled_frames:
        # An empty prediction file is NOT a model that detected nothing. Scoring
        # it would report 0% recall and read as a catastrophic model failure.
        return {"empty": True, "gt_frames": len(gt_labels.labeled_frames)}
    # Joining GT frames to PR frames is not trivial and neither obvious key works
    # everywhere, so the strategy is chosen per file and reported:
    #
    #   (filename, frame_idx) — correct for the SIDE runs, whose saved predictions
    #       kept the GT video names, and REQUIRED there because side frame_idx
    #       values repeat across videos.
    #   frame_idx alone       — required for the regenerated TOP predictions,
    #       because sleap-nn's predict() restores source video paths, so one frame
    #       is "labels.pkg.slp" in the predictions and "edits.pkg_full.slp" in the
    #       ground truth. Only valid when frame_idx is unique on both sides.
    #
    # A silent mis-join reads as catastrophic model failure, so coverage is
    # measured and a strategy that loses frames is rejected rather than used.
    def name_of(frame) -> str:
        return frame.video.filename if isinstance(frame.video.filename, str) else ""

    gt_frames = [f for f in gt_labels.labeled_frames]
    by_pair = {(name_of(f), f.frame_idx): f for f in pr_labels.labeled_frames}
    pair_coverage = sum(1 for f in gt_frames if (name_of(f), f.frame_idx) in by_pair)

    gt_idx = [f.frame_idx for f in gt_frames]
    pr_idx = [f.frame_idx for f in pr_labels.labeled_frames]
    idx_unique = len(set(gt_idx)) == len(gt_idx) and len(set(pr_idx)) == len(pr_idx)

    if pair_coverage == len(gt_frames):
        strategy = "(video, frame_idx)"
        predicted = {k: [instance_points(i) for i in v.instances] for k, v in by_pair.items()}
        key_of = lambda f: (name_of(f), f.frame_idx)  # noqa: E731
    elif idx_unique:
        strategy = "frame_idx (video names differ between GT and PR)"
        predicted = {
            f.frame_idx: [instance_points(i) for i in f.instances]
            for f in pr_labels.labeled_frames
        }
        key_of = lambda f: f.frame_idx  # noqa: E731
    else:
        raise SystemExit(
            f"{gt_path.parent.name}: cannot join GT to predictions. The "
            f"(video, frame_idx) key covers only {pair_coverage}/{len(gt_frames)} "
            f"frames and frame_idx is not unique. Refusing to report a partial score."
        )

    buckets: dict[str, dict[str, list]] = {
        regime: {"errors": [], "n_gt": 0, "n_pr": 0, "frames": 0}
        for regime in ("crossing", "separated")
    }
    buckets["join"] = strategy  # type: ignore[assignment]

    for frame in gt_labels.labeled_frames:
        gt = [instance_points(i) for i in frame.instances]
        gt = [g for g in gt if not np.isnan(g).all()]
        if len(gt) < 2:
            continue
        pr = predicted.get(key_of(frame), [])

        closest = min(
            (min_node_gap(gt[i], gt[j]) for i in range(len(gt)) for j in range(i + 1, len(gt))),
            default=float("inf"),
        )
        regime = "crossing" if closest < CROSSING_PX else "separated"
        bucket = buckets[regime]
        bucket["frames"] += 1
        bucket["n_gt"] += len(gt)
        bucket["n_pr"] += len(pr)
        bucket["errors"].extend(error for _, _, error in match_greedy(gt, pr))

    return buckets


def report(view: str) -> None:
    paths = load_paths()
    runs_root = Path(str(paths.asset_root).replace("assets", "")) / ROUND7 / view / "runs"
    if not runs_root.is_dir():
        runs_root = paths.asset_root.parent / ROUND7 / view / "runs"

    print(f"\n{'=' * 78}")
    print(f"{view.upper()} — crossing defined as GT instances < {CROSSING_PX:.0f} px apart")
    print("=" * 78)

    regenerated = paths.work_dir / "b03_top_inference"
    for label, run in ARCHITECTURES[view]:
        override = None
        if view == "top" and label in REGENERATED_TOP:
            gt_name, pr_name = REGENERATED_TOP[label]
            candidate = (regenerated / gt_name, regenerated / pr_name)
            if all(p.is_file() for p in candidate):
                override = candidate
                print(f"\n  [{label}] using REGENERATED predictions from {regenerated}")
        buckets = score(runs_root / run, override=override)
        if buckets is None:
            print(f"\n{label}: NO saved val predictions file in {run}")
            continue
        if buckets.get("empty"):
            print(f"\n{label}  [{run}]")
            print(
                f"  NOT SCORABLE — labels_pr.val.0.slp holds 0 frames against "
                f"{buckets['gt_frames']} GT frames.\n"
                f"  The predictions were never written. This is a missing artifact, not a\n"
                f"  model that detected nothing. Scoring it would report 0% recall and be\n"
                f"  read as catastrophic failure. Requires re-running inference."
            )
            continue
        print(f"\n{label}  [{run}]")
        print(f"  join: {buckets['join']}")
        for regime in ("separated", "crossing"):
            bucket = buckets[regime]
            if not bucket["frames"]:
                print(f"  {regime:10s} no frames")
                continue
            errors = np.array(bucket["errors"])
            recalls = " ".join(
                f"@{t:g}px {100.0 * (errors < t).sum() / bucket['n_gt']:5.1f}%" for t in TOLERANCES
            )
            print(
                f"  {regime:10s} {bucket['frames']:4d} frames, {bucket['n_gt']:4d} GT / "
                f"{bucket['n_pr']:4d} pred instances"
            )
            print(f"             recall {recalls}")
            if errors.size:
                print(
                    f"             matched localisation error: median "
                    f"{np.median(errors):5.2f} px, 90th {np.percentile(errors, 90):6.2f} px"
                )


def main() -> None:
    print("B0.3 — scoring round-7 validation predictions at crossings vs separated.")
    print("Side: predictions saved by the original runs. Top: regenerated by")
    print("tools/b03_run_top_inference.py, because all four top runs saved empty files.")
    print(f"Recall denominator is GT instances. Tolerances in px: {TOLERANCES}")
    for view in ("top", "side"):
        report(view)
    print(
        "\nCaveat: these are the runs' own validation splits, which are small and were\n"
        "drawn from the same pool as training. They compare architectures against each\n"
        "other, not against a held-out benchmark. Gate A's frozen split is still required."
    )


if __name__ == "__main__":
    main()
